export type PinyinParseResult =
    | { ok: true; syllables: [string, number][] }
    // offset と length は ph の中の誤りの位置
    | { ok: false; offset: number; length: number; text: string };

// 発音指定を音節ごとの (音節, 声調) に分解する
export function parsePinyin(ph: string): PinyinParseResult {
    const syllables: [string, number][] = [];
    for (const match of ph.matchAll(/\S+/g)) {
        const token = match[0];
        const parsed = /^([a-zA-ZüÜ:]+)([1-5])$/.exec(token);
        const syllable = parsed ? parsed[1].toLowerCase().replace(/ü|u:/g, 'v') : '';
        if (!parsed || !PINYIN_SYLLABLES.has(syllable)) {
            return { ok: false, offset: match.index ?? 0, length: token.length, text: token };
        }
        syllables.push([syllable, Number(parsed[2])]);
    }
    return { ok: true, syllables };
}

// 発音を指定する文字が、読み上げエンジンが読む漢字 (CJK 統合漢字の U+4E00〜U+9FA5) だけか。
// 1 文字が 1 音節に対応し、エンジンはこの範囲外の文字を読み飛ばすため
export function isHanOnly(text: string): boolean {
    return /^[\u4e00-\u9fa5]+$/.test(text);
}
